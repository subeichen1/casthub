const require = createRequire(import.meta.url);
const {
  buildUpdateHelperScript,
  downloadFile,
  parseChecksums,
  pickUpdateAssets,
  sha256File,
  writeUpdateHelperScript,
} = require("../desktop/updater.js");

test("parseChecksums supports GNU and star formats", () => {
  const hash = "a".repeat(64);
  const text = [
    "# generated by sha256sum",
    "",
    `${hash}  CastHub.exe`,
    `${hash.toUpperCase()} *checksums.txt`,
    "not a checksum line",
  ].join("\r\n");
  assert.deepEqual(parseChecksums(text), {
    "CastHub.exe": hash,
    "checksums.txt": hash,
  });
});

test("pickUpdateAssets finds case-insensitive assets and size", () => {
  const assets = [
    {
      name: "CASTHUB.EXE",
      browser_download_url: "https://github.com/example/repo/releases/download/v1/CastHub.exe",
      size: 12345,
    },
    {
      name: "checksums.txt",
      browser_download_url: "https://github.com/example/repo/releases/download/v1/checksums.txt",
      size: 100,
    },
  ];
  assert.deepEqual(pickUpdateAssets(assets), {
    exeUrl: assets[0].browser_download_url,
    checksumUrl: assets[1].browser_download_url,
    exeSize: 12345,
  });
});

test("pickUpdateAssets rejects missing exe or checksums", () => {
  assert.throws(() => pickUpdateAssets([]), /Release 缺少 CastHub.exe 或 checksums.txt/);
  assert.throws(
    () =>
      pickUpdateAssets([
        { name: "CastHub.exe", browser_download_url: "https://github.com/x/CastHub.exe" },
      ]),
    /Release 缺少 CastHub.exe 或 checksums.txt/,
  );
  assert.throws(
    () =>
      pickUpdateAssets([
        { name: "checksums.txt", browser_download_url: "https://github.com/x/checksums.txt" },
      ]),
    /Release 缺少 CastHub.exe 或 checksums.txt/,
  );
});

test("sha256File matches crypto hash", async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "casthub-sha-test-"));
  const file = path.join(dir, "sample.bin");
  try {
    const content = Buffer.from("CastHub updater hash test");
    fs.writeFileSync(file, content);
    const expected = crypto.createHash("sha256").update(content).digest("hex");
    assert.equal(await sha256File(file), expected);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test("downloadFile streams bytes and reports progress", async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "casthub-download-test-"));
  const destination = path.join(dir, "CastHub.exe");
  const body = Buffer.from("streamed update bytes");
  const originalFetch = globalThis.fetch;
  const progress = [];
  globalThis.fetch = async () =>
    new Response(body, {
      status: 200,
      headers: { "content-length": String(body.length) },
    });
  try {
    const result = await downloadFile("https://github.com/example/CastHub.exe", destination, (item) => {
      progress.push(item);
    });
    assert.deepEqual(fs.readFileSync(destination), body);
    assert.equal(result.received, body.length);
    assert.equal(progress[progress.length - 1].percent, 100);
  } finally {
    globalThis.fetch = originalFetch;
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test("helper script is ASCII PowerShell 5.1 compatible", () => {
  const script = buildUpdateHelperScript();
  assert.match(script, /param\(/);
  assert.match(script, /\$ParentPid/);
  assert.match(script, /Start-Process -FilePath \$Target/);
  assert.ok(
    [...script].every((character) => character.charCodeAt(0) <= 0x7f),
    "helper script should be ASCII",
  );
});

test("helper replaces target and preserves .old", { skip: process.platform !== "win32" }, async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "casthub-helper-test-"));
  const systemRoot = process.env.SystemRoot || "C:\\Windows";
  const targetSource = path.join(systemRoot, "System32", "where.exe");
  const sourceExe = path.join(systemRoot, "System32", "whoami.exe");
  const target = path.join(dir, "CastHub-test.exe");
  const source = path.join(dir, "update.exe");
  const logPath = path.join(dir, "casthub-update.log");
  try {
    assert.ok(fs.existsSync(targetSource), "where.exe should exist");
    assert.ok(fs.existsSync(sourceExe), "whoami.exe should exist");
    fs.copyFileSync(targetSource, target);
    fs.copyFileSync(sourceExe, source);
    const originalTargetHash = await sha256File(target);
    const sourceHash = await sha256File(source);

    const parent = spawn(process.execPath, ["-e", "setTimeout(() => {}, 80)"], { stdio: "ignore" });
    const helperPath = writeUpdateHelperScript(dir);
    assert.ok(fs.existsSync(helperPath));

    const args = [
      "-NoProfile",
      "-ExecutionPolicy",
      "Bypass",
      "-File",
      helperPath,
      "-Target",
      target,
      "-Source",
      source,
      "-ParentPid",
      String(parent.pid),
      "-LogPath",
      logPath,
    ];
    const helperExit = await new Promise((resolve, reject) => {
      const child = spawn("powershell.exe", args, { stdio: "ignore", windowsHide: true });
      const timer = setTimeout(() => {
        child.kill();
        reject(new Error("helper test timed out"));
      }, 20000);
      child.once("error", (error) => {
        clearTimeout(timer);
        reject(error);
      });
      child.once("close", (code) => {
        clearTimeout(timer);
        resolve(code == null ? -1 : code);
      });
    });
    parent.kill();

    assert.equal(helperExit, 0);
    assert.ok(fs.existsSync(target), "new target should exist");
    assert.ok(fs.existsSync(`${target}.old`), ".old backup should exist");
    assert.equal(await sha256File(target), sourceHash);
    assert.equal(await sha256File(`${target}.old`), originalTargetHash);
    const log = fs.readFileSync(logPath, "utf8");
    assert.match(log, /COPY_OK/);
    assert.match(log, /START_OK/);
    assert.match(log, /UPDATE_OK/);
  } finally {
    try {
      fs.rmSync(dir, { recursive: true, force: true, maxRetries: 10, retryDelay: 500 });
    } catch {
      // Windows 可能短暂锁定刚启动过的测试 exe；临时目录留给系统清理，不影响断言。
    }
  }
});
